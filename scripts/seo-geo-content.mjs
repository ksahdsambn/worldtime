function apply(locale, json) {
  const c = COPY[locale];
  if (!c) throw new Error(`missing copy: ${locale}`);
  json.App.openApp = c.openApp;
  json.Seo.citiesTitle = c.citiesTitle;
  json.Seo.aboutLink = c.aboutLink;
  json.Seo.privacyLink = c.privacyLink;
  json.Seo.sourceNote = c.sourceNote;
  const faq = json.Seo.faq;
  if (!Array.isArray(faq) || faq.length < 5) throw new Error(`${locale} Seo.faq`);
  faq[4].a = LIVE[locale];
  json.Landing.comparisonNote = c.comparisonNote;
  json.Landing.factLead = c.factLead;
  json.Landing.overlapTitle = c.overlapTitle;
  json.Landing.overlapBody = c.overlapBody;
  json.Landing.overlapNone = c.overlapNone;
  json.Landing.dstHeading = c.dstHeading;
  json.Landing.dstActive = c.dstActive;
  json.Landing.dstInactive = c.dstInactive;
  json.Landing.dstNone = c.dstNone;
  json.Landing.nextDst = c.nextDst;
  json.Landing.tzAbbrNote = c.tzAbbrNote;
  json.Landing.relatedCitiesTitle = c.relatedCitiesTitle;
  json.Landing.breadcrumbHome = c.breadcrumbHome;
  const lfaq = json.Landing.faq;
  if (!Array.isArray(lfaq) || lfaq.length < 3) throw new Error(`${locale} Landing.faq`);
  lfaq[2].a = MEET[locale];
  json.City = c.city;
  json.Country = c.country;
  json.About = c.about;
  json.Privacy = c.privacy;
  return json;
}

function shape(obj, prefix = "") {
  if (Array.isArray(obj)) {
    return [`${prefix}[]:${obj.length}`];
  }
  if (obj && typeof obj === "object") {
    return Object.keys(obj).sort().flatMap((k) => shape(obj[k], prefix ? `${prefix}.${k}` : k));
  }
  return [prefix];
}

const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const shapes = {};
for (const file of files) {
  const locale = file.replace(/\.json$/, "");
  const path = resolve(dir, file);
  const json = JSON.parse(readFileSync(path, "utf8"));
  apply(locale, json);
  writeFileSync(path, `${JSON.stringify(json, null, 2)}\n`);
  shapes[locale] = shape(json).join("\n");
  console.log("updated", file);
}
const baseline = shapes.en;
for (const [locale, s] of Object.entries(shapes)) {
  if (s !== baseline) {
    throw new Error(`shape mismatch: ${locale}`);
  }
}
