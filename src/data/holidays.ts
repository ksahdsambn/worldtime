/**
 * 判断某国家在某日期（YYYY-MM-DD）是否为公共假日。
 * 未收录国家返回 false（不影响热力图，仅失去节假日覆盖能力）。
 */
export function isHoliday(countryCode: string, isoDate: string): boolean {
  const list = HOLIDAYS[countryCode.toUpperCase()];
  if (!list) return false;
  return list.includes(isoDate);
}
