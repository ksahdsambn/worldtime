/**
 * 由国家代码与城市英文名派生稳定 id（slug）。
 * 同一国家同名城市会被视为同一记录。
 */
function makeId(countryCode: string, nameEn: string): string {
  const slug = nameEn
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
  return `${countryCode.toLowerCase()}-${slug}`;
}

/**
 * 构建后的城市记录表。
 *
 * 去重说明：makeId 按「国家代码 + 英文名 slug」派生 id，
 * 同一国家存在同名城市时（如中国"遂宁/睢宁"英文名均为 Suining）会产出重复 id。
 * 此处在构建数组阶段即做去重：冲突的后续记录追加序号后缀（如 cn-suining-2），
 * 保证 CITIES 数组与 CITY_BY_ID 映射的 id 完全一致，
 * 避免「搜索用数组、分享还原用映射」时拿不到同一记录的问题。
 */
export const CITIES: CityRecord[] = (() => {
  const seen: Record<string, true> = {};
  return CITY_TUPLES.map(([nameZh, nameEn, countryCode, timeZone]) => {
    const country = getCountry(countryCode);
    const baseId = makeId(countryCode, nameEn);
    let id = baseId;
    if (id in seen) {
      let i = 2;
      id = `${baseId}-${i}`;
      while (id in seen) id = `${baseId}-${++i}`;
    }
    seen[id] = true;
    return {
      id,
      nameZh,
      nameEn,
      countryCode,
      countryZh: country.nameZh,
      countryEn: country.nameEn,
      flag: country.flag,
      timeZone,
    };
  });
})();

/** id → 城市记录 映射（与 CITIES 数组的 id 一一对应）。 */
export const CITY_BY_ID: Record<string, CityRecord> = (() => {
  const map: Record<string, CityRecord> = {};
  for (const c of CITIES) {
    map[c.id] = c;
  }
  return map;
})();
